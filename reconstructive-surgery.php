        <h2>Eyelid Drooping (Ptosis)</h2>
        <p>Droopiness (ptosis) or sagging of the upper eyelid can occur as a result of birth defect, injury, muscle disorder, nerve disorder, or simply due to aging. It can obstruct vision when severe, and create a tired, aged or sleepy appearance. Eyelid ptosis may also cause excessive forehead wrinkling, headaches from forehead muscle contraction, abnormal head posture such as chin elevation to improve vision, and eye fatigue. When it is present since birth, severe droop might obstruct development of vision leading to a lazy (amblyopic) eye with subnormal vision. Thus, correction of drooping is of functional importance in children, and a functional as well as cosmetic concern in adults. Surgery can correct this problem by repairing the muscle and supporting the eyelid. Several surgical options are available, and the type of surgery used depends upon the severity of the droop.</p>
        <div class="recon-tabs">
            <div class="recon-tab-row">
                <span class="recon-tab active">Surgical Technique</span>
                <span class="recon-tab">Surgical Time and Recovery</span>
            </div>
            <div class="recon-tab-content" style="display:block;">
                <p>When the eyelid droop is mild, a simple tightening of the eyelid lifting muscle (levator) performed from the back of the eyelid (Mullerectomy) is needed. There is no skin scar in this surgery.
                    <br>Moderate droop requires tightening of the muscle that lifts the eyelid (levator), and is preferably done via skin incision that is typically hidden in the upper eyelid skin fold.
                    <br>In severe droop, tightening the eyelid muscle does not help. In that case, the eyelid has to be connected to the brow elevating muscle (frontalis) to effect eyelid lift. This surgery (called tarso-frontal sling surgery) can be preformed using various sling materials, and involves small (2-3mm) stab incisions over the eyelid and just above the brow. Sling surgeries are generally not permanent, and the eyelid often droops in a few years due to blinking and gravity, which act against the upward lift. A patient of sling surgery may therefore need multiple revisions of the surgery over his/her lifetime, possible through the same initial stab incisions.
                </p>
            </div>
            <div class="recon-tab-content">
                <p>Surgery for mild to moderate droop can be performed on an outpatient basis under local anesthesia and takes about 30 to 45 minutes. Discomfort is minimal, and stitches are removed in 5-7 days. Most patients are back to light work within a week. Minimal bruising may persist for 1-2 weeks. For severe ptosis (sling surgery) and for children, general anaesthesia is needed therefore necessitating a day’s admission.</p>
            </div>
        </div>
        <div class="note"><b>Notes:</b> Often times, ptosis surgery needs one or two sessions of suture adjustment (1-6 weeks after surgery) to match it to the other eye. 0.5 mm to 1 mm error remains in some severe cases, which is generally cosmetically well accepted. In case of severe ptosis, correction is optimal only in straight gaze. The eye appears slightly droopy in upgaze, and slightly wider in downgaze. Closure may also be incomplete, especially during sleep. Ptosis surgery may also be combined with upper eyelid blepharoplasty or lower eyelid blepharoplasty.</div>
