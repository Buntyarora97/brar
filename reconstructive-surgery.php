        <h2>Orbital Surgery</h2>
        <p>The Orbit (eye and surrounding bones) can be adversely affected by the presence of a tumor. The tumor could produce forward protrusion of the eye, reduce vision due to compression upon the nerve, or cause double vision. Most orbital tumors are benign (non-cancerous), however, some can be malignant (cancerous), especially in the elderly. Appropriate management of such cases needs a CT scan or MRI imaging followed by complete removal or partial (diagnostic) biopsy of the tumor.</p>
        <div class="recon-tabs">
