        <h2>Pterygium</h2>
        <p> Pterygium (pronounced “tur-RIDGE-ium”) is a benign thickening of the outer coating (conjunctiva) of the eye that grows onto the cornea. As a pterygium grows, it may become red and irritated. Eventually, it may cause visual disturbances by disrupting the normally smooth surface of the cornea. In severe cases, a pterygium can block a patient’s vision altogether. No-stitch pterygium surgery is made possible by the use of modern tissue adhesive*, composed of clotting proteins normally found in human blood. Tissue adhesive allows the surgeon to secure a conjunctival autograft in seconds rather than minutes. After about one week the tissue adhesive dissolves, leaving no residue, and the eye heals comfortably. </p>
        <div class="recon-tabs">
            <div class="recon-tab-row"> <span class="recon-tab active">Causes</span> <span class="recon-tab">Prevention</span> <span class="recon-tab">Treatment</span> <span class="recon-tab">History of Surgery</span> <span class="recon-tab">No-stitch Surgery</span> <span class="recon-tab">Technique for No-stitch Surgery</span> </div>
            <div class="recon-tab-content" style="display:block;">
                <p>UV radiation (usually from sunlight) is the most common cause of pterygium. This explains why pterygium occurs with increasing frequency in climates approaching the equator. Other causes include continuous exposure to dry, dusty environments. People who spend significant time in water sports (surfing or fishing) are particularly susceptible to pterygium because of the intense exposure to UV that occurs in these environments. When the eye is continuously assaulted by UV rays, the conjunctiva may thicken in a process similar to callus formation on the skin. The sensitive structures of the outer eye often can not comfortably tolerate this degenerative process, and irritation, redness, foreign body sensation, and ocular fatigue can result.</p>
            </div>
            <div class="recon-tab-content">
                <p>The best method of preventing pterygium is to regularly wear UV 400 rated sunglasses when outdoors in sunny conditions. Sunglasses with a wrap-around design provide better protection than those with large gaps between the sunglass frame and the skin around the eyes. Wearing a hat with a wide brim provides valuable additional protection.</p>
            </div>
            <div class="recon-tab-content">
                <p>In mild cases, pterygium redness and discomfort can be controlled with lubricant eye drops (artificial tears). When symptoms of redness, irritation, or blurred vision are resistant to conservative treatment, or when vision is affected by progressive growth of a pterygium, surgery is considered.</p>
            </div>
            <div class="recon-tab-content">
                <p>In pterygium surgery, the abnormal tissue is removed from the cornea and sclera (white of the eye). Over the years, pterygium surgery has evolved significantly, and modern pterygium surgery has a significantly higher success rate than conventional surgery. In traditional “bare sclera” pterygium removal, the underlying white of the eye (sclera) is left exposed. Healing occurs over two to four weeks with mild to moderate discomfort. Unfortunately, the pterygium may grow back in up to 50% of patients. In many cases, the pterygium grows back larger than its original size. Traditional “bare sclera” pterygium surgery has a high rate of re-growth. Occasionally, the pterygium grows back larger than the original. Over the years, surgeons have used several different techniques to lessen the likelihood of pterygium recurrence, including radiation treatment and the use of “antimetabolite” chemicals that prevent growth of tissue. Each of these techniques has risks that potentially threaten the health of the eye after surgery, including persistent epithelial defects (ulceration in the surface of the eye), and corneal melting.</p>
            </div>
            <div class="recon-tab-content">
                <p>Most cornea specialists today perform pterygium surgery with a conjunctival autograft because of a reduced risk of recurrence. In this technique, the pterygium is removed, and the cornea regains clarity. However, the gap in the mucous membrane (conjunctiva) tissue, where the pterygium was removed, is filled with a transplant of tissue that has been painlessly removed from underneath the upper eyelid. Although the procedure requires more surgical skill than traditional surgery, this “auto-graft” (self-transplant) helps prevent re-growth of the pterygium by filling the space where abnormal tissue would have re-grown. In conventional autograft surgery, stitches are used to secure the graft in place on the eye. These can cause discomfort for several weeks. The autograft is held in place with tiny stitches that may dissolve after a few weeks or can be removed in the surgeon’s office. Stitches on the eye frequently cause discomfort, however, after pterygium/autograft surgery. The desire for a quicker, more painless recovery has led to the development of no-stitch pterygium/autograft surgery.</p>
            </div>
            <div class="recon-tab-content">
                <p>No-stitch pterygium/autograft surgery allows most patients to return to work within one or two days of surgery. A research study on 85 patients with pterygium conducted at Harvard Eye Associates has shown that patients undergoing no-stitch surgery had significantly less pain after surgery than those having traditional surgery. The no-stitch technique also reduced surgery time from an average of 21 minutes to 14 minutes. No pterygium recurrences were found in any patients in the study.</p>
            </div>
            <div class="recon-tab-content">
                <p>In no-stitch surgery, the patient is lightly sedated to ensure comfort, and the eye is completely numbed, so there is no way to see the surgery occurring and no sensation of discomfort. The abnormal corneal tissue is removed and replaced with a thin graft of normal tissue. Over the next 2-3 weeks, the eye gradually returns to a normal appearance.</p>
            </div>
