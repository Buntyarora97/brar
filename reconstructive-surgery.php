        <h2>Surgery for a Watering Eye</h2>
        <p>Watery eye is usually a sign of blocked tear ducts resulting from infection, injury, or rarely a tumor. Tear duct surgery may be performed to open or bypass the duct and allow the tears to drain directly into the nose (Dacryocystorhinostomy, or simply DCR). Tear duct surgery can be performed through a small incision in the corner of the eye or with endoscopic surgery (with a tiny microscope) through the nose. When tear duct is blocked since birth (due to non-canalization), it can lead to watering since birth.</p>
        <div class="recon-tabs">
