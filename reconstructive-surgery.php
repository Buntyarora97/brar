        <h2>Thyroid Eye Disease</h2>
        <p>Thyroid eye disease (a condition of Graves’ disease or hyperthyroidism) causes the eyes to bulge forward and the eye aperture (gap between two eyelids) to widen. This leads to double vision, severe inflammation, discomfort, dry or watery eyes, corneal abrasions, infections, and possibly loss of vision. The initial (active) phase of thyroid eye disease involves frequent swelling of tissues around the eyes, double vision, and even reduction in vision in severe cases. Active phase is treated with medications to reduce the swelling. Fortunately, the active phase of most thyroid eye disease patients ends in 18-24 months. However, the deformities (raised eyelid, prominent eyeball, or squint) may persist, and now requires surgery.</p>
        <div class="recon-tabs">
            <div class="recon-tab-row"> <span class="recon-tab active">Surgical Time and Recovery</span> </div>
            <div class="recon-tab-content" style="display:block;">
                <p>Decompression surgery is typically performed first in the staged surgical management of thyroid eye disease. It involves expanding the bones of the eye socket to allow the eye to fall back. It can be performed under local or general anaesthesia depending upon the severity. Muscle surgery is performed next to alleviate double vision if present. Eyelid surgery is often the last stage of rehabilitation whereby the eyelids are lowered, yielding a more natural, aesthetically pleasing appearance and reducing the chance of future eye-related complications. Discomfort is controlled with medications after surgery, and lasts for a week. Stitches are removed in 5-7 days. Most patients are back to light work within a week.</p>
