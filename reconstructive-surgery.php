        <h2>Trauma and Maxillofacial Surgery</h2>
        <p>Trauma can affect any structure of the eyelid, eyeball and the surrounding bones (fracture) depending upon the mechanism and force of injury. Laceration of the eyelid needs meticulous placement of stitches to preserve its normal shape and function. Injury to the tear ducts (canaliculus) within the eyelids require special placement of silicone tubes within them to keep them open while the injured eyelid heals. A thorough examination is also done to find out if the eyeball is also injured. Fractures of the bone surrounding the eye (orbital walls) may cause the eye to sink back into its socket, lead to a facial deformity, poor eye movement, or loss of vision. A clinical examination combined with a CT scan of the orbit can easily detect any of this possibility. The presence of any retained foreign bodies also needs to be ruled out. Orbital fractures can now be repaired with minimal incisions through the inside of the eyelid or mouth. Most often, a barrier has to be placed to cover the fracture site. Excellent synthetic plates (polyethylene or silastic) are available for this purpose, or alternatively a small sliver of patient’s own bone can be safely removed from elsewhere and placed over the fracture site.</p>
