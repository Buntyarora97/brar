        function toggleFaq(element) {
            const answer = element.nextElementSibling;
            const icon = element.querySelector('i');
            
            if (answer.style.display === 'none' || answer.style.display === '') {
                answer.style.display = 'block';
                icon.className = 'fas fa-minus';
            } else {
                answer.style.display = 'none';
                icon.className = 'fas fa-plus';
            }
        }

        function calculateSuccess() {
            const prescription = document.getElementById('prescriptionRange').value;
            const resultDiv = document.getElementById('successResult');
            
            if (!prescription) {
                resultDiv.innerHTML = 'Please select your prescription range';
                return;
            }
            
            let successRate = '';
            let message = '';
            
            switch(prescription) {
                case 'low':
                    successRate = '98%';
                    message = 'Excellent candidate! Very high success rate for low prescriptions.';
                    break;
                case 'moderate':
                    successRate = '95%';
                    message = 'Great candidate! High success rate for moderate prescriptions.';
                    break;
                case 'high':
                    successRate = '85%';
                    message = 'Good candidate with considerations. Detailed evaluation needed.';
                    break;
                case 'hyperopia':
                    successRate = '92%';
                    message = 'Very good candidate! High success rate for hyperopia correction.';
                    break;
            }
            
            resultDiv.innerHTML = `<strong>Success Rate: ${successRate}</strong><br><small>${message}</small>`;
        }

