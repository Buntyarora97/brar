  <img src="attached_assets\generated_images\Squint_eye_alignment_diagram_66d1e2cf.webp" alt="Squint Exam" class="squint-img">
  <div class="squint-flex-row">
    <div>
      <p>
        Squint is a misalignment of the eyes such that the right and left eyes are pointed in different directions. Though it is a common condition among younger populations, affecting 2 to 4 percent of children, it may also appear later in life. The misalignment may be permanent or it may be temporary, occurring occasionally. The deviation may be in any direction: inward, outward, upward or downward.
      </p>
    </div>
  </div>

  <div class="content-section">
    <h2 class="sub-title">Causes of Squint</h2>
    <ul class="list-style">
      <li>Weakened muscles or abnormal nerve impulses to the eye muscles</li>
      <li>Hereditary</li>
      <li>Blurred or poor vision</li>
      <li>Pathology inside the eye, such as cataract</li>
    </ul>
  </div>

  <div class="content-section">
    <h2 class="sub-title">Signs and Symptoms</h2>
    <ul class="list-style">
      <li>The primary sign of squint is an eye that is not straight.</li>
      <li>A youngster may squint or close one eye in bright sunlight.</li>
      <li>Faulty depth perception may be present.</li>
      <li>Some children turn their faces or tilt their heads in a specific direction to use their eyes together.</li>
    </ul>
  </div>

  <div class="content-section">
    <h2 class="sub-title">Treatment</h2>
    <p>
      Parents often get the false impression that a child may “outgrow” the problem. If a child’s two eyes are pointed in different directions, examination by an ophthalmologist is necessary to determine the cause and to begin treatment.
    </p>
    <p>
      The goals of treatment are to preserve vision, straighten the eyes, and restore binocular vision. Treatment of squint depends upon the exact cause of the misaligned eyes. It can be directed towards unbalanced muscles or other conditions which are causing the eyes to point in two different directions. After a complete eye examination, including a detailed study of the inner parts of the eye, an ophthalmologist can recommend appropriate optical, medical, or surgical therapy.
    </p>
    <h3>Non-surgical treatment – Spectacles</h3>
    <p>
      Some squints are caused by refractive errors. In such cases, squint can be corrected by prescribing proper spectacles.
    </p>
  </div>

  <div class="content-section">
    <h2 class="sub-title">Squint Surgery</h2>
    <ul class="list-style">
      <li>
        Most patients require surgical correction. Surgery is done under general anesthesia in children and under local anesthesia in cooperating adults. The child should be free from acute illness to undergo general anesthesia. Parents should inform the doctor if the child has systemic problems such as cardiac disease or epilepsy.
      </li>
      <li>
        Routine investigations before surgery include a blood test and an X-ray of the chest.
      </li>
      <li>
        Surgery is done either on both eyes simultaneously or on one at a time.
      </li>
      <li>
        Surgery is done on eye muscles situated outside the eyeball. The principle of surgery is to weaken the stronger muscle and strengthen the weaker muscle. Either one or several muscles may be operated upon, depending on the type and severity of squint.
      </li>
      <li>
        After surgery, the eye is bandaged for one day.
      </li>
      <li>
        Eye drops are used for one month after surgery.
      </li>
      <li>
        Oral medication is not required except in a few cases.
      </li>
      <li>
        Hospital stay is only two hours after surgery.
      </li>
      <li>
        First follow-up is next day after surgery.
      </li>
    </ul>
  </div>
</div>

