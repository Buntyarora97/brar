        <h2>The LASIK Procedure</h2>
        
        <h3>Step 1: Creating the Corneal Flap</h3>
        <p>Using either a femtosecond laser or a microkeratome, a thin flap is created on the cornea's surface. This flap is gently lifted to access the underlying corneal tissue.</p>
        
        <h3>Step 2: Reshaping the Cornea</h3>
        <p>An excimer laser precisely removes microscopic amounts of tissue to reshape the cornea. The laser is programmed with your unique prescription to correct your specific vision problem.</p>
        
        <h3>Step 3: Repositioning the Flap</h3>
        <p>The corneal flap is carefully repositioned. It adheres naturally without the need for stitches. The flap acts as a natural bandage, promoting faster healing.</p>
        
