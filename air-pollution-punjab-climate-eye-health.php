            <h2>Introduction</h2>
            <p>Punjab is known for vibrant seasons — from hot, dusty summers to foggy, cold winters. But behind the beauty lies changing air quality, dust exposure, crop residue smoke (parali burning), and rising pollution levels that silently damage our eyes every day.</p>
            <p>Your eyes are among the first organs to suffer from pollution. Dust particles, smoke, and chemical pollutants cause irritation, allergies, dryness, and even long-term vision problems if left untreated.</p>
            <p>At Brar Eye Hospital Bathinda, we see hundreds of patients every year suffering from pollution-related eye problems — especially during October-November (post-harvest burning season) and winter fog months.</p>

            <h2>How Does Air Pollution Damage Your Eyes?</h2>
            <p>The air we breathe contains tiny particles called PM2.5 and PM10 — these are microscopic pollutants from vehicle exhaust, factory emissions, construction dust, and crop burning. When these particles come in contact with your eyes, they cause:</p>
            <ul>
                <li><strong>Eye Irritation & Redness:</strong> Pollutants trigger inflammation on the eye surface</li>
                <li><strong>Allergic Conjunctivitis:</strong> Itching, watering, and swelling of the eyes</li>
                <li><strong>Dry Eye Syndrome:</strong> Pollution damages the tear film, leading to chronic dryness</li>
                <li><strong>Burning Sensation:</strong> Chemical pollutants cause a stinging or burning feeling</li>
                <li><strong>Blurred Vision:</strong> Heavy smog reduces clarity and strains the eyes</li>
            </ul>

            <div class="highlight-box">
                <h3>Punjab-Specific Risk Factors</h3>
                <p>Punjab's unique climate and agricultural practices create specific eye health challenges:</p>
                <ul>
                    <li><strong>Parali Burning (Oct-Nov):</strong> Crop residue burning creates toxic smoke that severely irritates eyes</li>
                    <li><strong>Summer Dust Storms:</strong> Fine dust particles cause corneal scratches and allergies</li>
                    <li><strong>Winter Fog + Pollution:</strong> Cold air traps pollutants close to ground level</li>
                    <li><strong>Industrial Pollution:</strong> Factory emissions in industrial areas add to the burden</li>
                </ul>
            </div>

            <h2>Common Eye Problems Caused by Pollution</h2>
            <ol>
                <li><strong>Allergic Conjunctivitis:</strong> Red, itchy, watery eyes that worsen during high pollution days</li>
                <li><strong>Dry Eye Disease:</strong> Chronic dryness, gritty sensation, and discomfort</li>
                <li><strong>Blepharitis:</strong> Inflammation of eyelids due to pollutant deposits</li>
                <li><strong>Corneal Damage:</strong> Microscopic scratches from dust particles</li>
                <li><strong>Increased Infection Risk:</strong> Pollution weakens eye immunity, making infections more likely</li>
            </ol>

            <h2>Who Is Most at Risk?</h2>
            <ul>
                <li>Children and elderly people</li>
                <li>People who work outdoors (farmers, construction workers, traffic police)</li>
                <li>Contact lens wearers</li>
                <li>People with pre-existing eye conditions</li>
                <li>Those living near industrial areas or highways</li>
            </ul>

            <h2>How to Protect Your Eyes from Pollution</h2>
            <div class="highlight-box">
                <h3>Daily Protection Tips</h3>
                <ul>
                    <li><strong>Wear Protective Eyewear:</strong> Use wraparound sunglasses when going outside</li>
                    <li><strong>Use Lubricating Eye Drops:</strong> Artificial tears help wash away pollutants</li>
                    <li><strong>Avoid Rubbing Eyes:</strong> This pushes pollutants deeper and causes scratches</li>
                    <li><strong>Wash Eyes Regularly:</strong> Use clean water to rinse eyes after coming home</li>
                    <li><strong>Stay Indoors on High Pollution Days:</strong> Check AQI before planning outdoor activities</li>
                    <li><strong>Use Air Purifiers:</strong> Keep indoor air clean, especially in bedrooms</li>
                    <li><strong>Stay Hydrated:</strong> Drinking water helps maintain healthy tear production</li>
                </ul>
            </div>

            <h2>When to See an Eye Doctor</h2>
            <p>Don't ignore persistent eye problems. Visit Brar Eye Hospital Bathinda if you experience:</p>
