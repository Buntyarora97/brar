                <li>Severe itching or burning sensation</li>
                <li>Blurred or hazy vision</li>
                <li>Eye pain or sensitivity to light</li>
                <li>Discharge or crusting around eyes</li>
                <li>Swelling of eyelids</li>
            </ul>

