            <article class="eye-problem">
                <div class="problem-number">1</div>
                <h2>Refractive Errors (Nearsightedness, Farsightedness, and Astigmatism)</h2>
                
                <h3>What is it?</h3>
                <p>Refractive errors happen when the shape of your eye does not bend light properly, causing blurred vision. The most common ones are:</p>
                <ul>
                    <li><strong>Nearsightedness (Myopia):</strong> You can see close objects clearly, but far objects appear blurry.</li>
                    <li><strong>Farsightedness (Hyperopia):</strong> You can see distant objects clearly, but nearby objects look blurry.</li>
                    <li><strong>Astigmatism:</strong> Vision is distorted because of an uneven shape of the cornea.</li>
                </ul>

                <h3>Symptoms:</h3>
                <ul>
                    <li>Blurry vision</li>
                    <li>Squinting</li>
                    <li>Headaches</li>
                    <li>Eye strain</li>
                </ul>

                <h3>Prevention:</h3>
                <ul>
                    <li>Go for regular eye check-ups.</li>
                    <li>Wear prescribed glasses or contact lenses.</li>
                    <li>Consider LASIK surgery for permanent correction (available at advanced eye care hospitals like Brar Eye Hospital).</li>
                    <li>Avoid straining your eyes by taking breaks from screens.</li>
                </ul>
            </article>

            <article class="eye-problem">
                <div class="problem-number">2</div>
                <h2>Cataract</h2>
                
                <h3>What is it?</h3>
                <p>A cataract is clouding of the natural lens in your eye, which leads to blurry vision. It usually happens with age but can also be caused by diabetes, smoking, or injuries.</p>

                <h3>Symptoms:</h3>
                <ul>
                    <li>Cloudy or blurry vision</li>
                    <li>Difficulty seeing at night</li>
                    <li>Sensitivity to light</li>
                    <li>Colors looking faded</li>
                </ul>

                <h3>Prevention:</h3>
                <ul>
                    <li>Wear sunglasses to protect against harmful UV rays.</li>
                    <li>Eat foods rich in Vitamin C and E.</li>
                    <li>Quit smoking and limit alcohol.</li>
                    <li>Get regular eye exams after the age of 40.</li>
                    <li>If vision loss happens, cataract surgery is a safe and effective treatment.</li>
                </ul>
            </article>

            <article class="eye-problem">
                <div class="problem-number">3</div>
                <h2>Glaucoma</h2>
                
                <h3>What is it?</h3>
                <p>Glaucoma is an eye disease that damages the optic nerve, often caused by high pressure inside the eye. If untreated, it can lead to permanent vision loss.</p>

                <h3>Symptoms:</h3>
                <ul>
                    <li>Blurred vision</li>
                    <li>Eye pain</li>
                    <li>Headaches</li>
                    <li>Loss of side vision</li>
                    <li>Seeing halos around lights</li>
                </ul>

                <h3>Prevention:</h3>
                <ul>
                    <li>Regular eye check-ups (especially after age 40).</li>
                    <li>Early detection with eye pressure tests.</li>
                    <li>Avoid smoking and maintain a healthy lifestyle.</li>
                    <li>If diagnosed, use prescribed eye drops and treatments regularly.</li>
                </ul>
            </article>

            <article class="eye-problem">
                <div class="problem-number">4</div>
                <h2>Diabetic Retinopathy</h2>
                
                <h3>What is it?</h3>
                <p>This is a serious eye condition caused by diabetes. High blood sugar damages blood vessels in the retina, leading to vision problems.</p>

                <h3>Symptoms:</h3>
                <ul>
                    <li>Blurred vision</li>
                    <li>Dark spots or floaters</li>
                    <li>Vision loss in severe cases</li>
                </ul>

                <h3>Prevention:</h3>
                <ul>
                    <li>Keep blood sugar, blood pressure, and cholesterol under control.</li>
                    <li>Have yearly diabetic eye exams.</li>
                    <li>Eat a healthy diet and exercise daily.</li>
                    <li>Visit a trusted eye hospital for regular screening.</li>
                </ul>
            </article>

            <article class="eye-problem">
                <div class="problem-number">5</div>
                <h2>Dry Eyes</h2>
                
                <h3>What is it?</h3>
                <p>Dry eyes happen when your eyes do not produce enough tears or the tears evaporate too quickly. This can make your eyes feel irritated or uncomfortable.</p>

                <h3>Symptoms:</h3>
                <ul>
                    <li>Burning or stinging in eyes</li>
                    <li>Redness</li>
                    <li>Blurred vision</li>
                    <li>Feeling like something is in the eye</li>
                </ul>

                <h3>Prevention:</h3>
                <ul>
                    <li>Avoid direct air from fans or AC blowing on your eyes.</li>
                    <li>Use artificial tears (eye drops).</li>
                    <li>Blink often while using computers or mobile phones.</li>
                    <li>Drink plenty of water and include omega-3 fatty acids in your diet.</li>
                    <li>See a doctor if the problem continues.</li>
                </ul>
            </article>

            <article class="eye-problem">
                <div class="problem-number">6</div>
                <h2>Conjunctivitis (Pink Eye)</h2>
                
                <h3>What is it?</h3>
                <p>Conjunctivitis is an infection or inflammation of the conjunctiva, making the white part of your eye red. It is often caused by infection, allergies, or irritants.</p>

                <h3>Symptoms:</h3>
                <ul>
                    <li>Redness in the eye</li>
                    <li>Itching or irritation</li>
                    <li>Discharge or watery eyes</li>
                    <li>Crust on eyelids in the morning</li>
                </ul>

                <h3>Prevention:</h3>
                <ul>
                    <li>Wash your hands often.</li>
                    <li>Avoid touching or rubbing your eyes.</li>
                    <li>Do not share towels or eye makeup.</li>
                    <li>Use prescribed medicines if it is bacterial.</li>
                </ul>
            </article>

            <article class="eye-problem">
                <div class="problem-number">7</div>
                <h2>Age-Related Macular Degeneration (AMD)</h2>
                
                <h3>What is it?</h3>
                <p>AMD affects the macula (the central part of the retina), leading to loss of central vision. It usually affects older adults.</p>

                <h3>Symptoms:</h3>
                <ul>
                    <li>Difficulty seeing in the center of vision</li>
                    <li>Trouble recognizing faces</li>
                    <li>Straight lines appearing wavy</li>
                </ul>

                <h3>Prevention:</h3>
                <ul>
                    <li>Eat a diet rich in leafy greens, nuts, and fish.</li>
                    <li>Avoid smoking.</li>
                    <li>Protect eyes from UV light with sunglasses.</li>
                    <li>Get eye exams regularly after age 50.</li>
                </ul>
            </article>

            <article class="eye-problem">
                <div class="problem-number">8</div>
                <h2>Eye Allergies</h2>
                
                <h3>What is it?</h3>
                <p>Eye allergies occur when the eyes react to allergens like dust, pollen, smoke, or pet dander.</p>

                <h3>Symptoms:</h3>
                <ul>
                    <li>Itchy eyes</li>
                    <li>Redness</li>
                    <li>Watery eyes</li>
                    <li>Swollen eyelids</li>
                </ul>

                <h3>Prevention:</h3>
                <ul>
                    <li>Avoid exposure to allergens.</li>
                    <li>Keep windows closed during pollen season.</li>
                    <li>Wash your hands and face regularly.</li>
                    <li>Use anti-allergy eye drops if needed.</li>
                </ul>
            </article>

            <article class="eye-problem">
                <div class="problem-number">9</div>
                <h2>Eye Strain (Digital Eye Strain or Computer Vision Syndrome)</h2>
                
                <h3>What is it?</h3>
                <p>Spending long hours on mobile phones, laptops, or TV can cause eye strain. It is becoming very common today.</p>

                <h3>Symptoms:</h3>
                <ul>
                    <li>Headache</li>
                    <li>Blurred vision</li>
                    <li>Dry eyes</li>
                    <li>Neck and shoulder pain</li>
                </ul>

                <h3>Prevention:</h3>
                <ul>
                    <li>Follow the 20-20-20 rule: Every 20 minutes, look at something 20 feet away for 20 seconds.</li>
                    <li>Adjust screen brightness.</li>
                    <li>Use blue-light filter glasses.</li>
                    <li>Take regular breaks from digital screens.</li>
                </ul>
            </article>

            <article class="eye-problem">
                <div class="problem-number">10</div>
                <h2>Eye Injuries</h2>
                
                <h3>What is it?</h3>
                <p>Accidents, dust, or foreign objects can cause minor or serious eye injuries.</p>

                <h3>Symptoms:</h3>
                <ul>
                    <li>Pain</li>
                    <li>Redness</li>
                    <li>Blurred vision</li>
                    <li>Tearing</li>
                </ul>

                <h3>Prevention:</h3>
                <ul>
                    <li>Wear protective eyewear while working with tools, chemicals, or during sports.</li>
                    <li>Avoid rubbing eyes if something enters them.</li>
                    <li>Wash gently with clean water and see a doctor immediately if the injury is serious.</li>
                </ul>
            </article>
