        <div class="faq-section" style=" padding: 20px;">
            <details>
                <summary>HOW IS GLAUCOMA DETECTED?</summary>
                <p>
                    Regular eye examinations by the ophthalmologist leads to detection.<br>
                    The complete and painless examination includes (among other tests):<br>
                    - Tonometry – Measurement of intraocular pressure<br>
                    - Gonioscopy – Inspection of drainage angle of the eye<br>
                    - Ophthalmoscopy – Evaluation of optic nerve damage<br>
                    - Perimetry – Testing the visual field of each eye<br>
                    - GDXVCC – Retinal nerve fiber layer analyser<br>
                    - OCT – Retinal nerve fiber thickness and optic cup–disc size
                </p>
            </details>
            <details>
                <summary>WHO IS AT RISK FOR GLAUCOMA?</summary>
                <ul>
                    <li>Family history of glaucoma</li>
                    <li>Age over 45 years and not regular with eye exams</li>
                    <li>Near-sightedness (myopia)</li>
                    <li>Any injury to your eyes</li>
                    <li>Secondary to cataract, inflammation, tumours</li>
                    <li>Long-term cortisone medication</li>
                </ul>
            </details>
            <details>
                <summary>About Symptoms</summary>
                <ul>
                    <li>Poor night vision</li>
                    <li>Sensation of blind area</li>
                    <li>Headaches in early morning or after dusk</li>
                    <li>Pain in eye, especially with smoky vision</li>
                    <li>Halos around lights</li>
                </ul>
            </details>
            <details>
                <summary>About Risk Factors</summary>
                <p>
                    People with high pressures have greater risk. Advancing age, high myopia, family history, diabetes, past injuries, surgeries, anaemia, or shock increase risk. High risk with no optic nerve damage: monitored as 'glaucoma suspect.'
                </p>
            </details>
            <details>
                <summary>About Early Detection</summary>
                <p>
                    Regular eye examination by an ophthalmologist is the best way to detect glaucoma. During a complete work up for glaucoma, your ophthalmologist will measure the intraocular pressure (tonometry), inspect the drainage angle of the eye (gonioscopy), evaluate for optic nerve damage (ophthalmoscopy), and test the visual field of each eye (perimetry). These tests must be repeated regularly to monitor the progress of disease.
                </p>
            </details>
            <details>
                <summary>Management</summary>
                <p>
                    Glaucoma can't be cured, but can be controlled and further damage slowed/halted. Requires lifelong treatment and regular checkups.
                <ul>
                    <li><b>Medical:</b> Eye drops (sometimes pills) to reduce eye pressure, used regularly at prescribed intervals.</li>
                    <li>Possible side effects: Stinging, redness, blurring, headaches. Rare: pulse, heartbeat, breathing changes. Pills may cause tingling, drowsiness, loss of appetite, bowel/kidney issues.</li>
                    <li><b>Laser surgery:</b> Trabeculoplasty (open angle); Iridotomy (angle-closure).</li>
                    <li><b>Surgery:</b> Trabeculectomy (advanced cases), glaucoma valve implants (if other surgeries fail).</li>
                </ul>
                The goal is to lower the eye pressure to a safe level that prevents further optic nerve damage.<br>
                The success of your treatment depends entirely on teamwork between you and your ophthalmologist. It is therefore important to communicate with your doctor and keep all the follow-up appointments. If you don’t, glaucoma could be stealing your sight without your knowledge!
                </p>
            </details>
