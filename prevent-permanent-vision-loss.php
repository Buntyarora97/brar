            <h2 class="br-eye-heading-accent">2. Types of Advanced Eye Screenings</h2>
            <div class="br-eye-feature-list">
                <div class="br-eye-feature-card"><strong>a) Optical Coherence Tomography (OCT)</strong> OCT uses light waves to capture high-resolution cross-sectional images of the retina. This helps detect early glaucoma, macular degeneration, and retinal swelling.</div>
                <div class="br-eye-feature-card"><strong>b) Fundus Photography</strong> This imaging technique captures detailed photographs of the retina, optic nerve, and blood vessels, helping identify diabetic retinopathy, hypertension-related damage, and other retinal conditions.</div>
                <div class="br-eye-feature-card"><strong>c) Visual Field Testing</strong> Also known as perimetry, this test measures peripheral vision. It is especially useful for detecting early glaucoma.</div>
                <div class="br-eye-feature-card"><strong>d) Corneal Topography</strong> This maps the curvature of the cornea and is essential for diagnosing conditions like keratoconus and planning corrective surgeries.</div>
                <div class="br-eye-feature-card"><strong>e) Retinal Imaging & Fluorescein Angiography</strong> These tests visualize blood flow and detect leakage or blockages in retinal vessels, crucial for managing diabetic and vascular eye diseases.</div>
            </div>
