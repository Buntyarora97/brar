        function calculateIdealAge() {
            const birthYear = document.getElementById('birthYear').value;
            const resultDiv = document.getElementById('ageResult');
            
            if (!birthYear) {
                resultDiv.innerHTML = 'Please enter your birth year';
                return;
            }
            
            const currentYear = new Date().getFullYear();
            const age = currentYear - parseInt(birthYear);
            
            let message = '';
            
            if (age < 18) {
                message = `You are ${age} years old. Wait until age 18 for eligibility.`;
            } else if (age >= 18 && age <= 25) {
                message = `You are ${age} years old. Good candidate! Ensure 1+ year prescription stability.`;
            } else if (age >= 26 && age <= 45) {
                message = `You are ${age} years old. Perfect age range for laser surgery!`;
            } else if (age >= 46 && age <= 60) {
                message = `You are ${age} years old. Good candidate with presbyopia considerations.`;
            } else {
                message = `You are ${age} years old. Consultation needed for candidacy assessment.`;
            }
            
            resultDiv.innerHTML = message;
        }

