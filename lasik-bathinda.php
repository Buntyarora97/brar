        <h2>LASIK: Laser Vision Correction</h2>
        
        <p>LASIK or Laser in situ Keratomileusis reshapes the cornea by using a laser beam to alter its curvature. It corrects vision by altering the refractive power of the eye by producing a calculated change in the curvature of the cornea. The image of the outside world in now focused sharply on the retina.</p>
        
        <p>The procedure is relatively simple and comfortable. Eyes of the patient are made numb by instilling anesthetic eye drops. Using an instrument called microkeratome a thin flap of corneal tissue is raised. The excimer Laser then reshapes the cornea by removing a predetermined precise amount of tissue from inner cornea. The corneal flap is then repositioned back where it bonds without the need of stitches.</p>
        
        <h3>LASIK (Laser Insitu Keratomielusis)</h3>
        <p>A superficial flap of cornea is lifted with an instrument called Microkeratome. Then within 60 seconds U/V light and energy pulses from excimer laser precisely sculpt (reshape) the corneal bed. By adjusting the pattern of laser beam, it is possible to correct high levels of near sightedness (myopia) and moderate levels of far sightedness (hypermetropia) and astigmatism. After the corneal bed is reshaped the flap of cornea is replaced in its original position.</p>
    </div>
    
