        <div class="faq-item">
            <div class="faq-question">
                What is wavefront and how does wavefront LASIK work?
            </div>
            <div class="faq-answer">
                <div class="faq-answer-content">
                    <p>Light falling on the cornea [the front surface of the eye] has a smooth curvature - referred to as a "wavefront". As this smooth wavefront shape courses through the various optics of the eye, ocular aberrations [imperfections] are induced. It results in an irregular wavefront curvature reaching the retinal surface, which degrades the retinal image quality. An aberration-free eye would result in a smooth wavefront image on the retinal surface.</p>
                    <p>Wavefront-guided/adopted/customized LASIK, also referred to as "customized ablation" or custom LASIK performs corrections based on individual wavefront measurements.</p>
                    <p>Current refractive procedures such as traditional or standard LASIK correct lower order aberrations such as spherical and cylindrical numbers alone. However, higher order aberrations affect the quality of vision and may not significantly affect the vision as read on the chart. It is these subtle deviations from the ideal optical system, which can be corrected by wavefront procedures, and thereby improve image quality.</p>
                </div>
            </div>
        </div>
        
