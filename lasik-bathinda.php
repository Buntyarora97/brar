        <h2>Surface Ablation: Epi-LASIK</h2>
        <!--<img src="assets/laser/epilasik-procedure.webp" alt="Epi-LASIK Surface Ablation Procedure" class="section-image">-->
        <h3>Here's how it works:</h3>
        <ul>
            <li>During Epilasik the eye is numbed using anesthetic eye drops and eyelid holder placed to prevent blinking.</li>
            <li>A dissecting instrument called an epikeratome is used to slice off a thin layer of the cornea about 10 percent of corneal thickness.</li>
            <li>Computer controlled laser is then applied to reshape the cornea.</li>
            <li>Finally the epithelial flap is rolled back to its original position (the flap may also be discarded) and a bandage contact lens is applied for 3-5 days.</li>
        </ul>
