            <h2 class="br-eye-heading-accent">1. What Are Bags Under the Eyes?</h2>
            <p class="br-eye-text-block">Bags under the eyes are mild swelling or puffiness that appears in the lower eyelid region. They occur when the tissues around the eyes, including muscles and fat, retain fluid or sag. While often associated with aging, under-eye bags can affect anyone, regardless of age or gender.</p>
