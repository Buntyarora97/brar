            <h2 class="br-eye-heading-accent">2. Common Causes of Bags Under the Eyes</h2>
            <div class="br-eye-feature-list">
                <div class="br-eye-feature-card"><strong>a) Aging</strong><br>As we age, skin loses collagen and elasticity, and muscles weaken. Fat that normally supports the eyes can shift into the lower eyelids, causing puffiness.</div>
                <div class="br-eye-feature-card"><strong>b) Fluid Retention</strong><br>Excess fluid can accumulate due to high salt intake, hormonal changes, or sleeping positions, leading to swelling under the eyes.</div>
                <div class="br-eye-feature-card"><strong>c) Lack of Sleep</strong><br>Poor or insufficient sleep can exacerbate puffiness and dark circles, making bags under the eyes more noticeable.</div>
                <div class="br-eye-feature-card"><strong>d) Allergies</strong><br>Allergic reactions can cause inflammation, leading to swelling and dark circles. Common allergens include dust, pollen, and certain foods.</div>
                <div class="br-eye-feature-card"><strong>e) Genetics</strong><br>Heredity plays a role in under-eye puffiness. Some individuals naturally have weaker connective tissue or thinner skin around the eyes.</div>
                <div class="br-eye-feature-card"><strong>f) Lifestyle Factors</strong><br>Smoking, alcohol consumption, and chronic stress can accelerate aging and fluid retention, contributing to puffiness.</div>
                <div class="br-eye-feature-card"><strong>g) Medical Conditions</strong><br>Less commonly, persistent bags may indicate thyroid issues, kidney problems, or sinus infections. Consulting a doctor is recommended if puffiness is sudden or severe.</div>
            </div>
