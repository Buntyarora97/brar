            <h2 class="br-eye-heading-accent">1. What is a Cataract?</h2>
            <p class="br-eye-text-block">A cataract is a clouding of the eye’s natural lens, which lies behind the iris and pupil. This clouding affects light passing through the lens, leading to blurred vision, glare, and difficulty seeing in low light. Cataracts typically develop slowly, and symptoms may go unnoticed in the early stages.</p>
            <p class="br-eye-text-block">Common symptoms include: Blurred or dim vision, sensitivity to light and glare, difficulty seeing at night, fading or yellowing of colors, and double vision in one eye. Untreated cataracts can significantly affect daily life, making tasks like reading, driving, or recognizing faces challenging.</p>
        </section>

        <section class="br-eye-article-section">
            <h2 class="br-eye-heading-accent">2. When is Cataract Surgery Needed?</h2>
            <p class="br-eye-text-block">Cataract surgery is usually recommended when vision problems interfere with daily activities, glasses or contact lenses no longer provide adequate correction, or cataracts prevent proper monitoring of other eye conditions. Early intervention can prevent accidents, maintain quality of life, and improve overall vision health.</p>
        </section>

        <section class="br-eye-article-section">
            <h2 class="br-eye-heading-accent">3. Types of Cataract Surgery</h2>
            <div class="br-eye-feature-list">
                <div class="br-eye-feature-card"><strong>a) Phacoemulsification (Phaco):</strong> The most common method. A tiny incision is made, and an ultrasonic device breaks the clouded lens into small pieces for removal.</div>
                <div class="br-eye-feature-card"><strong>b) Extracapsular Cataract Extraction (ECCE):</strong> Used for advanced cataracts where the lens is too dense for phacoemulsification. The lens is removed in one piece.</div>
                <div class="br-eye-feature-card"><strong>c) Femtosecond Laser-Assisted Cataract Surgery (FLACS):</strong> A laser is used to make precise incisions and soften the lens before removal, enhancing accuracy.</div>
            </div>
            <p class="br-eye-text-block" style="margin-top:20px;"><strong>d) Types of Intraocular Lenses (IOLs):</strong> Options include Monofocal, Multifocal, Toric (for astigmatism), and Accommodative IOLs.</p>
        </section>

        <section class="br-eye-article-section">
            <h2 class="br-eye-heading-accent">4. Preparing for Cataract Surgery</h2>
            <p class="br-eye-text-block">Proper preparation ensures a smooth surgical experience: Comprehensive eye examination, discussion of IOL options, temporary discontinuation of certain medications, and arranging for transportation after surgery.</p>
        </section>

        <section class="br-eye-article-section">
            <h2 class="br-eye-heading-accent">5. Cataract Surgery Procedure</h2>
            <p class="br-eye-text-block">The procedure typically takes 15–30 minutes per eye under local anesthesia. The lens is broken up and removed, followed by IOL implantation. Most patients notice improved vision within a few days.</p>
