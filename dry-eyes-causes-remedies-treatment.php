                <h2>What Are Dry Eyes?</h2>
                <p>Dry eyes mean your eyes are not getting enough moisture. Tears are important because they keep your eyes healthy and clear. Without enough tears, your eyes may feel uncomfortable, and your vision may even get blurry.</p>
                
                <h3>Tears are made of three layers:</h3>
                <ul>
                    <li><strong>Oil layer</strong> – prevents tears from drying too fast.</li>
                    <li><strong>Water layer</strong> – provides moisture.</li>
                    <li><strong>Mucus layer</strong> – helps spread tears evenly.</li>
                </ul>
                <p>If any of these layers is not balanced, you may get dry eyes.</p>
            </article>

            <article class="eye-problem">
                <h2>Common Causes of Dry Eyes</h2>
                <p>There are many reasons why your eyes may feel dry. Some of the most common causes include:</p>

                <h3>1. Age</h3>
                <p>As we grow older, our body makes fewer tears. People above 50 often face dry eye problems.</p>

                <h3>2. Screen Time</h3>
                <p>Looking at phones, laptops, or TVs for a long time reduces blinking. Less blinking means fewer tears to keep your eyes moist.</p>

                <h3>3. Environment</h3>
                <p>Dry air, dust, wind, smoke, or air conditioners can dry out your eyes.</p>

                <h3>4. Contact Lenses</h3>
                <p>Wearing lenses for long hours can reduce oxygen supply and cause dryness.</p>

                <h3>5. Medications</h3>
                <p>Some medicines like antihistamines, antidepressants, or blood pressure tablets can reduce tear production.</p>

                <h3>6. Health Conditions</h3>
                <p>Diabetes, thyroid issues, rheumatoid arthritis, and other diseases can increase the risk of dry eyes.</p>

                <h3>7. Hormonal Changes</h3>
                <p>Women, especially after menopause, may face more dry eye issues due to hormonal changes.</p>

                <h3>8. Eye Surgery</h3>
                <p>Surgeries like LASIK may temporarily cause dryness.</p>
            </article>

            <article class="eye-problem">
                <h2>Symptoms of Dry Eyes</h2>
                <p>You may have dry eyes if you notice:</p>
                <ul>
                    <li>Burning or stinging feeling in your eyes</li>
                    <li>Redness</li>
                    <li>Blurred vision</li>
                    <li>Feeling like sand is in your eyes</li>
                    <li>Stringy mucus around the eyes</li>
                    <li>Sensitivity to light</li>
                    <li>Trouble wearing contact lenses</li>
                    <li>Watery eyes (yes, dry eyes can sometimes make your eyes water as a reaction)</li>
                </ul>
            </article>

            <article class="eye-problem">
                <h2>Home Remedies for Dry Eyes</h2>
                <p>The good news is that many people can manage dry eyes at home with simple changes. Here are some effective remedies:</p>

                <h3>1. Blink More Often</h3>
                <p>When using a computer or phone, remind yourself to blink often. This helps spread tears evenly.</p>

                <h3>2. Follow the 20-20-20 Rule</h3>
                <p>Every 20 minutes, look at something 20 feet away for 20 seconds. This reduces strain and dryness.</p>

                <h3>3. Use Artificial Tears</h3>
                <p>Lubricating eye drops (available at pharmacies) can give quick relief. Always choose preservative-free drops if using them often.</p>

                <h3>4. Stay Hydrated</h3>
                <p>Drink at least 7–8 glasses of water daily. Dehydration can make dry eyes worse.</p>

                <h3>5. Eat Eye-Friendly Foods</h3>
                <p>Include foods rich in Omega-3 fatty acids (like flaxseeds, walnuts, fish) and Vitamin A (like carrots, spinach, and sweet potatoes) for better eye health.</p>

                <h3>6. Humidifier at Home</h3>
                <p>Using a humidifier adds moisture to the air, especially in air-conditioned or heated rooms.</p>

                <h3>7. Warm Compress</h3>
                <p>Placing a warm, clean cloth on closed eyes can help release blocked oil glands in your eyelids.</p>

                <h3>8. Clean Eyelids</h3>
                <p>Gently cleaning eyelids with a cotton pad and warm water can reduce irritation.</p>

                <h3>9. Limit Contact Lens Use</h3>
                <p>If your eyes feel too dry, reduce the number of hours you wear lenses.</p>

                <h3>10. Protect Your Eyes Outdoors</h3>
                <p>Wear sunglasses to protect eyes from wind, dust, and sunlight.</p>
            </article>

            <article class="eye-problem">
                <h2>When to See a Doctor</h2>
                <p>While home remedies work for many, sometimes dry eyes need professional care. Visit an eye specialist if:</p>
                <ul>
                    <li>Symptoms last for more than 1–2 weeks despite home care</li>
                    <li>Your eyes are very red or painful</li>
                    <li>Your vision becomes blurry or unstable</li>
                    <li>You have thick discharge or swelling</li>
                    <li>You find it hard to do daily activities due to discomfort</li>
                </ul>
            </article>

            <article class="eye-problem">
                <h2>Medical Treatments for Dry Eyes</h2>
                <p>Doctors may recommend treatments like:</p>
                <ul>
                    <li>Prescription eye drops to reduce inflammation</li>
                    <li>Ointments for night use</li>
                    <li>Punctal plugs (tiny devices to block tear drainage and keep eyes moist)</li>
                    <li>Special contact lenses made for dry eyes</li>
                    <li>Treating underlying conditions like diabetes or thyroid problems</li>
                </ul>
            </article>

            <article class="eye-problem">
                <h2>How to Prevent Dry Eyes in the Future</h2>
