                <ul>
                    <li>Take regular breaks from screens</li>
                    <li>Wear protective glasses outdoors</li>
                    <li>Keep your room air clean and moist</li>
                    <li>Avoid smoking or secondhand smoke</li>
                    <li>Follow a healthy diet and stay hydrated</li>
                    <li>Visit your eye doctor regularly</li>
                </ul>
