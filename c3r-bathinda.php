    <div class="c3r-section-title">What is keratoconus?</div>
    <div class="c3r-desc">
        Keratoconus is a progressive condition affecting the cornea of the eye. The cornea is the clear window in front of the eye. It is a curved structure. The precise shape of the curve allows it to act as a lens, projecting an image into the eye. The cornea is made up of bundles of a protein called ‘collagen’. These bundles are normally held tightly together by chemical links between the collagen strands. This ensures that the shape of the cornea is constant. The problem with the keratoconic cornea is that the normal chemical links between collagen strands are deficient, causing the cornea to be unusually elastic. The pressure inside the eye then pushes the cornea into a distorted, conical shape. This spoils the quality of the image projected into the eye, and the vision becomes progressively blurred.<br><br>
        Keratoconus affects about 1 in 7000 people.
    </div>

