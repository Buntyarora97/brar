            <div class="highlight-box">
                <h3>Paradox: Why Do Dry Eyes Water?</h3>
                <p>It seems contradictory, but dry eyes often produce excessive tears. When your eyes become too dry, the body responds by producing emergency "reflex tears." However, these tears are watery and lack the oils needed to properly lubricate the eye, so they don't solve the underlying dryness problem.</p>
            </div>

            <h2>Who Is at Higher Risk?</h2>
            <ul>
                <li>People over 50 years of age</li>
                <li>Women (especially post-menopausal)</li>
                <li>Contact lens wearers</li>
                <li>Those who spend long hours on screens</li>
                <li>People with autoimmune conditions (Sjogren's syndrome, rheumatoid arthritis)</li>
                <li>Those taking certain medications (antihistamines, antidepressants, blood pressure drugs)</li>
                <li>People who have had LASIK or cataract surgery</li>
            </ul>

            <h2>Home Remedies for Winter Dry Eyes</h2>
            <div class="remedy-grid">
                <div class="remedy-card">
                    <h4>Use a Humidifier</h4>
                    <p>Add moisture to indoor air, especially in bedrooms and workspaces. Aim for 40-60% humidity levels.</p>
                </div>
                <div class="remedy-card">
                    <h4>Stay Hydrated</h4>
                    <p>Drink plenty of water even in winter. Warm water, herbal teas, and soups all count toward hydration.</p>
                </div>
                <div class="remedy-card">
                    <h4>Blink Consciously</h4>
                    <p>Make a habit of blinking fully and frequently, especially during screen time. Set reminders if needed.</p>
                </div>
                <div class="remedy-card">
                    <h4>Warm Compresses</h4>
                    <p>Apply a warm, damp cloth to closed eyes for 5-10 minutes to help release natural oils from eyelid glands.</p>
                </div>
            </div>

            <h2>Winter Eye Care Tips</h2>
            <div class="winter-tip-box">
                <h3>Daily Protection Strategies</h3>
                <ol>
                    <li><strong>Wear Protective Eyewear:</strong> Use wraparound glasses or goggles outdoors to block cold wind</li>
                    <li><strong>Position Away from Heaters:</strong> Don't sit directly in front of room heaters or blowers</li>
                    <li><strong>Take Screen Breaks:</strong> Follow the 20-20-20 rule (every 20 min, look 20 feet away for 20 sec)</li>
                    <li><strong>Avoid Rubbing Eyes:</strong> This worsens irritation and can introduce infections</li>
                    <li><strong>Use Preservative-Free Drops:</strong> Artificial tears help maintain moisture throughout the day</li>
                    <li><strong>Eat Omega-3 Rich Foods:</strong> Fish, flaxseed, and walnuts support healthy tear production</li>
                    <li><strong>Get Adequate Sleep:</strong> Rest helps eyes recover and produce quality tears</li>
                </ol>
            </div>

            <h2>When to See an Eye Doctor</h2>
            <p>While mild dry eye can be managed at home, visit Brar Eye Hospital Bathinda if you experience:</p>
            <ul>
                <li>Symptoms that persist despite home remedies</li>
                <li>Severe pain or discomfort</li>
                <li>Vision changes or blurriness</li>
                <li>Eye redness that doesn't improve</li>
                <li>Sensitivity to light</li>
                <li>Feeling of something stuck in the eye</li>
                <li>Discharge or crusting around eyes</li>
            </ul>

            <h2>Professional Treatment Options</h2>
