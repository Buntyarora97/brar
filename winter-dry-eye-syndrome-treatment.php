            <h2>Winter Eye Problems in Punjab</h2>
            <p>Punjab winters are pleasant, but they often come with an unwelcome companion — dry, itchy, burning eyes. This condition is known as Winter Dry Eye Syndrome, and it affects millions of people during the cold months.</p>
            <p>During winter, the air becomes cold and dry. Indoor heating further reduces humidity, creating an environment that pulls moisture from your eyes. At Brar Eye Hospital Bathinda, we see a significant increase in dry eye cases from November through February.</p>

            <h2>Why Does Winter Worsen Dry Eyes?</h2>
            <ul>
                <li><strong>Low Humidity:</strong> Cold air holds less moisture than warm air</li>
                <li><strong>Indoor Heating:</strong> Heaters, blowers, and radiators dry out indoor air</li>
                <li><strong>Cold Winds:</strong> Wind accelerates tear evaporation from the eye surface</li>
                <li><strong>Reduced Blinking:</strong> We tend to blink less when cold</li>
                <li><strong>Less Water Intake:</strong> People drink less water in winter, causing dehydration</li>
                <li><strong>Fog and Pollution:</strong> Winter fog traps pollutants close to ground level</li>
            </ul>

            <h2>Common Symptoms</h2>
