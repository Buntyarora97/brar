            <ul>
                <li><strong>Comprehensive Dry Eye Evaluation:</strong> Testing tear quality, quantity, and eye surface health</li>
                <li><strong>Prescription Eye Drops:</strong> Anti-inflammatory drops to treat underlying causes</li>
                <li><strong>Punctal Plugs:</strong> Tiny devices that help retain tears on the eye surface</li>
                <li><strong>Meibomian Gland Expression:</strong> Clearing blocked oil glands in the eyelids</li>
                <li><strong>Intense Pulsed Light (IPL):</strong> Advanced treatment for chronic dry eye</li>
                <li><strong>Customized Treatment Plans:</strong> Tailored approach based on your specific dry eye type</li>
            </ul>

            <h2>Lifestyle Changes for Long-Term Relief</h2>
            <ol>
                <li>Maintain indoor humidity levels between 40-60%</li>
                <li>Drink 8-10 glasses of water daily</li>
                <li>Include omega-3 fatty acids in your diet</li>
                <li>Reduce caffeine and alcohol intake (they dehydrate)</li>
                <li>Quit smoking (smoke irritates and dries eyes)</li>
                <li>Get regular eye checkups</li>
                <li>Manage screen time and take regular breaks</li>
                <li>Clean eyelids daily with mild cleanser</li>
            </ol>

