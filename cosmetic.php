    <div class="section-heading">Enucleation and Evisceration</div>
    <div class="sub-heading">Cosmetically unacceptable blind eye</div>
    A blind eye may become shrunken or have an unsightly appearance. A scleral shell resembles a large contact lens and is made of hard acrylic painted to resemble an eye. A scleral shell is worn in front of your natural eye.
    <br><br>
    <div class="sub-heading">Ocularist</div>
    A medical practitioner who specializes in making “artificial” or prosthetic eyes.In many cases, the natural blind eye is too sensitive to tolerate a scleral shell, and you may elect to have the unsightly eye removed. After surgery, you can be fit with an artificial eye, improving your appearance.
    <br><br>
    <div class="sub-heading">Infection</div>
    Occasionally an eye can become so severely infected that there is no hope of recovery. The eye is then removed in order to prevent the spread of the infection to the tissue around the eye and to the rest of the body. In most cases of infection, an evisceration is performed. An evisceration removes the internal contents of the eye and leaves the sclera to prevent spread of the infection to the tissues around the eye. If the sclera, the outer covering of the eye, is also infected then an enucleation, with complete removal of the eye, is necessary.
    <br><br>
    <div class="sub-heading">Tumor</div>
    Some eyes with a cancerous growth are removed to prevent spread of the cancer. In these cases, an enucleation with complete removal of the eyeball is necessary.
    <br><br>
    <div class="sub-heading">Trauma</div>
    Sometimes the eye gets so badly injured that no functional vision is possible. Even repairing it will not givde any benfit rather can be a cuase of sympathetic ophthalmia. In these cases as well evisceration + implant followed by prosthesis gives a good cosmetic rehabilitation to the patient.
</div>

