    <div class="section-heading">
        <a class="custom-link" href="#">What happens when your eyeball is removed?</a>
    </div>
    At the time of enucleation or evisceration an implant is placed within the orbit or within the remaining scleral shell to replace the missing socket volume and to allow the remaining ocular muscles to function. The implant is buried in the socket tissue. When the socket has healed it will appear like a pink pocket behind the eyelids. The buried implant will move in the pocket with movement of the other eye.
    
    <div class="sub-heading" style="margin-top:18px;">Type of Implant</div>
    After deciding on the procedure to remove the eye, you and your surgeon should discuss the type of orbital implant that will be placed into the socket during surgery.
    <br><br>
    In general, there are two types of implants in common use. One type of implant is a solid ball, sometimes called a Jardon. In many people a solid implant is the best choice. A solid implant produces an acceptable socket appearance and has a very low rate of complications. However, with time, this implant may slip in the orbit causing a sunken appearance to the socket. The second type of implant is an “integrated” implant made of porous material. The tissue from your orbit will grow into small the small holes, in effect making the implant part of your body. This ingrowth of tissue prevents slippage within the socket. But integrated implants have their own set of complications and hence becoming less popular.
    
    <div class="sub-heading" style="margin-top:18px;">Post-operative Care</div>
    In many cases you will admitted to the hospital overnight after the procedure for pain control. Usually the acute pain resolves after a day or two. However, many people describe a dull headache after surgery, which lasts about two weeks. After surgery the operated eye will be patched for 1-2 days. While the patch is in place, no special care of the socket is needed except to keep the bandage dry. After removing the patch you will be instructed to place an antibiotic ointment into the socket. Please do not clean or rub the inside of the socket. For two weeks after surgery please do not expose the socket to dirt, go swimming, or lift objects over twenty pounds. At the time of surgery the surgeon places a conformer in the socket. This will remain in place until you are fit for your artificial eye by an ocularist. You should wait at least four weeks after an evisceration and four to six weeks after an enucleation before the ocularist fits an artificial eye. If an artificial eye is not fit within a few months of the procedure the socket may shrink, and it may become difficult to wear an appropriate artificial eye.

    <div class="sub-heading" style="margin-top:18px;">Custom made prosthesis</div>
    After your socket has healed, you may obtain an artificial eye, called a prosthesis. A prosthesis is a hard acrylic shell which is held in position by the eyelids. A prosthesis is made by an ocularist. The ocularist takes a mold of you socket, from which the custom prosthesis is made. It typically takes at least two visits to make a prosthesis
    
    <div class="sub-heading" style="margin-top:18px;">Secondary Surgery in People Wearing Artificial Eyes</div>
    In some cases, people wearing an artificial eye will require additional surgery. After wearing a prosthesis for a number of years, the soft tissue of the eyelids and sockets can change.
    
    <div class="note">Lower lid looseness and Socket Shrinkage</div>
    After supporting the ocular prosthesis for a number of years, the lower lid may loosen. This results in exposure of the prosthesis below the iris. This is often associated with shrinkage of the lower socket or “pocket”. This may result in the artificial eye falling out. The lower lid is tightened with an incision at the outside corner of the eyelids. A shrunken pocket can be expanded with a graft from the inside of the lower lip or with donated material.

    <div class="note">Upper lid Drooping and Sinking</div>
    After surgery most patients have a somewhat sunken appearance of the upper lid. You may require a larger orbital implant or a fat graft can be taken from your hip and placed into the upper lid to fill out the eyelid.Also, the upper lid can droop, called ptosis. Modifying the ocular prosthesis can raise the eyelid. If modifying the implant is not effective, the muscle which raises the eyelid can be tightened.

    <div class="note">Orbital Implant Exposure</div>
    The tissue in the socket can break down, causing exposure of the orbital implant. In patients with an older style implant, covered with metallic mesh, the implant itself must be removed and replaced. If an “integrated” implant becomes exposed, the implant can usually be left in the socket. During surgical repair, the exposed area is smoothed and covered with a graft.
</div>
