            <h2>Who Is Eligible for SMILE Pro Surgery?</h2>
            <p>A person may be eligible if they:</p>
            <ul>
                <li>Are above 18 years old</li>
                <li>Have stable vision prescription</li>
                <li>Have healthy corneas</li>
                <li>Have myopia or astigmatism within treatable limits</li>
            </ul>
            <p>A detailed consultation with an experienced ophthalmologist is necessary to determine eligibility.</p>

            <h2>What Happens During the SMILE Pro Procedure?</h2>
            <ol>
                <li><strong>Eye Examination:</strong> Doctor performs detailed eye scans and measurements.</li>
                <li><strong>Laser Treatment:</strong> A femtosecond laser creates a lenticule inside the cornea.</li>
                <li><strong>Lenticule Removal:</strong> Surgeon removes the lenticule through a tiny incision.</li>
                <li><strong>Vision Correction:</strong> The cornea's shape changes, allowing light to focus correctly on the retina.</li>
            </ol>

