            <h3>Procedure</h3>
            <ul>
                <li><strong>LASIK:</strong> Requires creating a corneal flap</li>
                <li><strong>SMILE Pro:</strong> Uses a tiny incision without a flap</li>
            </ul>
            <h3>Recovery Time</h3>
            <ul>
                <li><strong>LASIK:</strong> Recovery within a few days</li>
                <li><strong>SMILE Pro:</strong> Often faster recovery with minimal discomfort</li>
