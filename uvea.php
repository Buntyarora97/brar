        <div class="faq-item">
          <button class="faq-question">What causes uveitis?<span class="faq-arrow">&#8250;</span></button>
          <div class="faq-answer">
            Causes of uveitis are many.<br>
            It may result from an infection (bacteria like tuberculosis, viruses like herpes, parasites like toxoplasmosis).<br>
            It may also be related to an autoimmune disease (with or without involvement of other parts of the body). This essentially is when our immune system recognizes a part of our own body as foreign and elicits a reaction in the form of uveitis.<br>
            The uveitis may be the presenting manifestation of an underlying systemic disease.<br>
            It can occur as a result of injury to the eye.<br>
            It can occur due to other disorders in the eye like cataract and retinal detachment.<br>
            Sometimes the cause is not known at the first instance. As we follow-up the patient over a period of time, we may be able to pick up new clues or signs suggestive of a systemic disease. In such cases, they are labeled as idiopathic (cause not known) at the initial visit.
          </div>
        </div>
