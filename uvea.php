        <div class="faq-item">
          <button class="faq-question">Why is early diagnosis of uveitis important?<span class="faq-arrow">&#8250;</span></button>
          <div class="faq-answer">
            Uveitis is the 3rd leading cause of blindness. Inflammation of the uvea can affect the cornea, retina, sclera and other vital parts of the body. Inflammation inside the eye is a medical emergency because, untreated, it will lead to vision loss. Damage to the eye is preventable if detected early and treated adequately.
          </div>
        </div>
        <div class="faq-item">
          <button class="faq-question">How is uveitis treated?<span class="faq-arrow">&#8250;</span></button>
          <div class="faq-answer">
            The treatment of uveitis aims to achieve the following:<br>
            Relief of pain and discomfort (when present)<br>
            To prevent sight loss due to the disease or its complications<br>
            To treat the cause of the disease where possible.<br><br>
            Medical treatment of uveitis must be aggressive to prevent glaucoma, to prevent scarring of the structures inside the eye and to prevent possible blindness.<br>
            Different medications are used to control the original cause of uveitis, if known and to minimize the inflammation itself.<br>
            Eye drops especially steroids (to reduce inflammation and pain) and pupil dilators (to widen the pupil and relax the muscles within the eye) are the main medications used to treat uveitis.<br>
            For deeper inflammations, oral medicines eye injections or intravenous injections of steroids may be necessary. More severe cases of uveitis and those intolerant to steroids may require treatment with immunosuppressive agents.<br>
            Complications such as glaucoma, cataract or new blood vessel formation (neovascularization) also may need treatment in the course of the disease. If complications are advanced, conventional surgery or laser surgery may be necessary.
          </div>
        </div>
