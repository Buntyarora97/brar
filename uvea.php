          <button class="faq-question">What are the symptoms of uveitis?<span class="faq-arrow">&#8250;</span></button>
          <div class="faq-answer">
            Depending on the structure involved, the symptoms can vary from:<br>
            Pain<br>
            Redness<br>
            Inability to see light (photophobia)<br>
            Black spots moving in front of the eye<br>
            Blurring or reduction in vision
          </div>
