          <div class="faq-answer">
            The duration of treatment varies from person to person and also depends on the type and cause of uveitis. Simple forms of uveitis, for example, may respond to treatment within days and may not recur.<br>
            Chronic (long term, recurring) forms of uveitis that threaten vision can be very difficult to cure and require persistence on the part of the treating physician(s) and patient.<br>
            The length of time required to get the disease into a durable remission on steroids or immunosuppressants is difficult to quantify and is very individualistic but a minimum of 2 years is a reasonable estimate.<br>
            With appropriate, targeted treatment, most people with uveitis will become well controlled and progress to remission. Once in remission from uveitis, you should expect to have regular follow-up visits to our doctor to make sure that the disease remains in remission.
