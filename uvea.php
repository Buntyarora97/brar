        <div class="faq-item">
          <button class="faq-question">How is an ophthalmic evaluation done in a patient with uveitis?<span class="faq-arrow">&#8250;</span></button>
          <div class="faq-answer">
            An initial examination of the eye will be done. This includes the recording of the visual acuity by reading a chart (to check if the vision has decreased), slit lamp examination; (in which a narrow beam of light is shone into the eye so that a magnifying lens can closely examine the highlighted portion of the eye). Intraocular pressure recording (a painless test done by a tonometer); fundus examination (in which the pupil is widened so that the ophthalmologist can look into the eye and see structures in the back of the eye).<br>
            Because uveitis can be caused by so many different things (infections/autoimmune diseases) diagnosis may require detailed laboratory investigations and a referral to a uveitis specialist.
          </div>
        </div>
        <div class="faq-item">
          <button class="faq-question">What does a uveitis specialist do?<span class="faq-arrow">&#8250;</span></button>
          <div class="faq-answer">
            A uveitis specialist is an ophthalmologist with a special, specific interest in uveitis and who has become proficient in the diagnosis and management of patients with uveitis. He or she has received adequate training in the field of uveitis. A detailed medical history is elicited.<br>
            As uveitis can occur due to infection or an underlying autoimmune disease, it is necessary to discover and treat these conditions as well. The results obtained in the routine laboratory tests and or imaging will be analyzed by the uveitis specialist.<br>
            Many times a repeat in serologic testing may be needed. Specialized imaging of the eye and its structures may be required. Specialized blood tests related to the immune system may also be ordered to obtain a diagnosis. Depending on the type of uveitis, a sample of the fluid from the eye may also be sent to obtain a diagnosis by molecular diagnostic techniques.<br>
            As uveitis may be related to a systemic disease, a cross consultation with a rheumatologist, a pulmonologist or a physician may also be done.<br>
